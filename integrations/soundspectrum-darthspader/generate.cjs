"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { WORD, ROW_INTERVALS, NATIVE_STEPS, WARP_CONTROLS, PCM_GAIN, PCM_WARP, FFT_GAIN, FFT_WARP, MAX_DEFORMATION, createGeometry, createAudioWarp, deformPoint } = require("./geometry.cjs");

const NAME = "Rabbit Hole - darthspader";
const PACKAGE_NAME = "RabbitHole.Darthspader.package";
const format = (value) => Number(value.toFixed(5)).toString();
const matrix = (rows) => `{${rows.map((row) => `{${row.map(format).join(",")}}`).join(",")}}`;

function waveShape(geometry) {
  const coordinates = (component) => geometry.contours.map((contour) => contour.points.map((point) => point[component]));
  return `// Original lowercase ${WORD} outline geometry, generated by generate.cjs.
// No factory geometry, installed-font outlines, image overlays or playback hooks.
// Each NUM instance is one closed contour; disconnected letters never join.
// A geometry loads once; B caches a shared signed-PCM and FFT spatial field.
// y'=y+F(original x), x'=x: bowls/counters warp together and letter gaps stay fixed.
// Three-tap spatial filtering limits jagged spikes; no clock-driven position.
// Vertical warp <= ${format(MAX_DEFORMATION)} glyph units; 48 audio controls/frame.
Aspc=1
NUM=${geometry.contours.length}
Stps=${NATIVE_STEPS}
ConB=1
Vers=310

A0="${matrix(coordinates(0))}"
A1="${matrix(coordinates(1))}"
A2="vectorLR(${WARP_CONTROLS}, 0, 1)"

B0=".86 * min(X_EXTENTS / ${format(geometry.halfWidth)}, Y_EXTENTS / ${format(geometry.halfHeight + MAX_DEFORMATION)})"
B1="clamp(BASS)"
B2="select(ID, B2, ${PCM_GAIN} * mag(A2))"
B3="select(ID, B3, clamp(${FFT_GAIN} * fft(.02 + .9 * A2)) - clamp(${FFT_GAIN} * fft(.02 + .9 * (1 - A2))))"
B4="select(ID, B4, ${format(PCM_WARP)} * B2 / (1 + abs(B2)) + ${format(FFT_WARP)} * B3)"
B5="select(ID, B5, .25 * map1D(B4, clamp(A2 - 1 / ${WARP_CONTROLS - 1}), 1) + .5 * B4 + .25 * map1D(B4, clamp(A2 + 1 / ${WARP_CONTROLS - 1}), 1))"
B6="row(A0, ID)"
B7="row(A1, ID)"

C0="map1D(B6, s, 1)"
C1="map1D(B7, s, 1)"
C2="clamp((C0 + ${format(geometry.halfWidth)}) / ${format(geometry.width)})"
C3="map1D(B5, C2, 1)"

X0="B0 * C0"
Y0="B0 * (C1 + C3)"
LWdt="1.45 + .35 * B1"
Pen=".84 + .15 * B1"
`;
}

function colorMap() {
  return `// Original bounded purple/lilac palette; intensity 0 stays black.
H=".76"
S=".78 - .35 * i ^ 2"
V="i"
Vers=310
`;
}

function flowField() {
  return `// Neutral original mapping: no rotation or spatial smearing of the letters.
Aspc=0
srcX="x"
srcY="y"
Vers=310
`;
}

function packageSource() {
  return `# Original removable Rabbit Hole package. Loaded by SoundSpectrum's host.
def ExportPackage(inPathname):
    pkg = VisPackage(inPathname)
    pkg.DefaultEntryConfigType = 'WaveShape'
    pkg.EntryRegex = r'(.*)\\.(txt)$'
    pkg.AddEntryTree('WaveShapes', {'ConfigType': 'WaveShape'})
    pkg.AddEntryTree('ColorMaps', {'ConfigType': 'ColorMap'})
    pkg.AddEntryTree('FlowFields', {'ConfigType': 'FlowField'})
    return pkg
`;
}

function svgPreview(geometry, audio = false) {
  const width = 1400;
  const height = 650;
  const scale = 1180 / geometry.width;
  const toSvg = ([x, y]) => `${format(width / 2 + x * scale)},${format(height / 2 - y * scale)}`;
  const warp = audio ? createAudioWarp({
    sampleAt: (u) => 0.6 * Math.sin(2 * Math.PI * 7 * u) + 0.2 * Math.sin(2 * Math.PI * 13 * u),
    spectrumAt: (u) => 0.55 * Math.exp(-(((u - 0.17) / 0.08) ** 2)) + 0.22 * Math.exp(-(((u - 0.65) / 0.14) ** 2))
  }) : undefined;
  const paths = geometry.contours.map((contour) => {
    const points = Array.from({ length: NATIVE_STEPS + 1 }, (_, index) => deformPoint(contour, index / NATIVE_STEPS, warp, geometry.width));
    return `<path d="M${points.map(toSvg).join(" L")} Z"/>`;
  }).join("\n");
  const label = audio ? "GEOMETRY PREVIEW / signed PCM + spectrum deformation" : "GEOMETRY PREVIEW / original lowercase contours";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title description">
<title id="title">Original lowercase ${WORD} geometry preview</title>
<desc id="description">${audio ? "Synthetic bounded audio sample." : "Undeformed letter outlines."} These are the same contour tables used by the native WaveShape, not a SoundSpectrum screenshot or video.</desc>
<rect width="${width}" height="${height}" fill="#07020e"/>
<text x="48" y="58" fill="#aa91bd" font-family="sans-serif" font-size="18">${label}</text>
<g fill="none" stroke="#cda7f2" stroke-width="2.5" stroke-linejoin="round" stroke-linecap="round">${paths}</g>
<text x="48" y="604" fill="#aa91bd" font-family="sans-serif" font-size="16">Original path geometry · ${geometry.contours.length} independent contours · no font or raster overlay</text>
</svg>\n`;
}

function generate(destination = __dirname) {
  const geometry = createGeometry();
  const files = {
    [`${PACKAGE_NAME}/_package.py`]: packageSource(),
    [`${PACKAGE_NAME}/WaveShapes/${NAME}.txt`]: waveShape(geometry),
    [`${PACKAGE_NAME}/ColorMaps/${NAME}.txt`]: colorMap(),
    [`${PACKAGE_NAME}/FlowFields/${NAME}.txt`]: flowField(),
    "preview/darthspader-geometry.svg": svgPreview(geometry),
    "preview/darthspader-audio-sample.svg": svgPreview(geometry, true)
  };
  for (const [relative, content] of Object.entries(files)) {
    const filename = path.join(destination, relative);
    fs.mkdirSync(path.dirname(filename), { recursive: true });
    fs.writeFileSync(filename, content, "utf8");
  }
  return { name: NAME, packageName: PACKAGE_NAME, word: WORD, contours: geometry.contours.length, tableValues: geometry.contours.length * (ROW_INTERVALS + 1) * 2 + WARP_CONTROLS, nativePointsPerFrame: geometry.contours.length * NATIVE_STEPS, audioControlsPerFrame: WARP_CONTROLS, files: Object.keys(files) };
}

if (require.main === module) console.log(JSON.stringify(generate(), null, 2));
module.exports = { NAME, PACKAGE_NAME, waveShape, colorMap, flowField, packageSource, svgPreview, generate };
